export function t(key,values={}){const row=strings[key];if(!row)throw new Error('Missing translation: '+key);return row[languages.indexOf(language)].replace(/\{(\w+)\}/g,(_,name)=>String(values[name]??''));}
export function setLanguage(next){if(!languages.includes(next))throw new Error('Unsupported language');language=next;try{localStorage.setItem('fuel-language',next);}catch{}}
export function translatePage(){document.documentElement.lang=localeFor(language);document.title=t('title');for(const node of document.querySelectorAll('[data-i18n]'))node.textContent=t(node.dataset.i18n);for(const node of document.querySelectorAll('[data-i18n-placeholder]'))node.placeholder=t(node.dataset.i18nPlaceholder);for(const node of document.querySelectorAll('[data-i18n-aria]'))node.setAttribute('aria-label',t(node.dataset.i18nAria));document.getElementById('language').value=language;}
